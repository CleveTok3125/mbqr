#!/usr/bin/env python3
"""Generate BankDirectory.kt from the public VietQR bank directory.

Run from the repository root:

    python3 tools/update_banks.py

The generated file is committed so builds never depend on the network. The
``code`` field is written exactly as the API returns it; do not normalize it.
"""

from __future__ import annotations

import json
import pathlib
import re
import unicodedata
import urllib.request

API_URL = "https://api.vietqr.io/v2/banks"
ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "app/src/main/java/vn/io/elsutm/mbqr/vietqr/BankDirectory.kt"

BIN_PATTERN = re.compile(r"[0-9]{6}\Z")
UNSAFE_CATEGORIES = {"Cc", "Cf", "Zl", "Zp"}
MAX_PREFIX_LENGTH = 32
MAX_NAME_LENGTH = 100


def kotlin_string(value: str) -> str:
    """Return a Kotlin string literal body with syntax-level escaping."""
    escaped: list[str] = []
    for char in value:
        if char == "\\":
            escaped.append("\\\\")
        elif char == '"':
            escaped.append('\\"')
        elif char == "$":
            escaped.append("\\$")
        elif char == "\r":
            escaped.append("\\r")
        elif char == "\n":
            escaped.append("\\n")
        elif char == "\t":
            escaped.append("\\t")
        elif (
            ord(char) < 0x20
            or ord(char) == 0x7F
            or unicodedata.category(char) in UNSAFE_CATEGORIES
        ):
            escaped.append(f"\\u{ord(char):04x}")
        else:
            escaped.append(char)
    return "".join(escaped)


def require_text(value: object, field: str, max_length: int) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{field} must be a non-empty string")
    if len(value) > max_length:
        raise ValueError(f"{field} is longer than {max_length} characters")
    if any(unicodedata.category(char) in UNSAFE_CATEGORIES for char in value):
        raise ValueError(f"{field} contains a control or format character")
    return value


def validate_bank(bank: object) -> dict:
    if not isinstance(bank, dict):
        raise TypeError("bank entry must be an object")

    bin_value = str(bank.get("bin", ""))
    if not BIN_PATTERN.fullmatch(bin_value):
        raise ValueError(f"invalid BIN: {bin_value!r}")

    prefix = require_text(bank.get("code"), "code", MAX_PREFIX_LENGTH)
    short_name = require_text(
        bank.get("shortName") or bank.get("short_name") or bank.get("name"),
        "shortName",
        MAX_NAME_LENGTH,
    )

    supported = bank.get("transferSupported")
    if supported not in (0, 1):
        raise ValueError(f"invalid transferSupported for {bin_value}: {supported!r}")

    return {
        "bin": bin_value,
        "prefix": prefix,
        "shortName": short_name,
        "transferSupported": supported == 1,
    }


def fetch_banks() -> list[dict]:
    request = urllib.request.Request(
        API_URL,
        headers={"User-Agent": "mbqr-bank-directory/1"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        payload = json.load(response)

    raw_banks = payload.get("data")
    if not isinstance(raw_banks, list):
        raise SystemExit("VietQR returned no bank list")

    banks: list[dict] = []
    seen: set[str] = set()
    for raw_bank in raw_banks:
        try:
            bank = validate_bank(raw_bank)
        except (TypeError, ValueError) as error:
            hint = raw_bank.get("bin") if isinstance(raw_bank, dict) else None
            entry = f" BIN {hint}" if hint else ""
            raise SystemExit(f"invalid bank entry{entry}: {error}") from error
        if bank["bin"] in seen:
            raise SystemExit(f"duplicate BIN: {bank['bin']}")
        seen.add(bank["bin"])
        banks.append(bank)

    if len(banks) < 50:
        raise SystemExit(f"refusing to write only {len(banks)} banks")

    return sorted(banks, key=lambda bank: bank["bin"])


def render(banks: list[dict]) -> str:
    lines = [
        "package vn.io.elsutm.mbqr.vietqr",
        "",
        "/**",
        " * NAPAS bank directory taken from the public VietQR bank list.",
        " * Source: https://api.vietqr.io/v2/banks",
        " *",
        " * Generated by tools/update_banks.py. Do not edit manually.",
        " */",
        "data class BankInfo(",
        "    val bin: String,",
        "    val prefix: String,",
        "    val shortName: String,",
        "    val transferSupported: Boolean,",
        ")",
        "",
        "object BankDirectory {",
        "",
        "    private val banks: Map<String, BankInfo> = mapOf(",
    ]

    for bank in banks:
        lines.append(
            f'        "{kotlin_string(bank["bin"])}" to BankInfo('
            f'"{kotlin_string(bank["bin"])}", '
            f'"{kotlin_string(bank["prefix"])}", '
            f'"{kotlin_string(bank["shortName"])}", '
            f"{str(bank['transferSupported']).lower()}),"
        )

    lines.extend(
        [
            "    )",
            "",
            "    fun find(bin: String): BankInfo? = banks[bin]",
            "",
            "    internal fun all(): Collection<BankInfo> = banks.values",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    banks = fetch_banks()
    rendered = render(banks)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT.with_suffix(".kt.tmp")
    temporary.write_text(rendered, encoding="utf-8")
    temporary.replace(OUTPUT)
    print(f"wrote {OUTPUT} ({len(banks)} banks)")


if __name__ == "__main__":
    main()
